const Tutorial tutorialSync = Tutorial(
  id: 'sync-webdav',
  title: '全平台同步（坚果云）',
  summary: '手机和电脑不用连同一个 Wi-Fi，也能互相同步待办、课程资料和专注记录',
  group: TutorialGroup.sync,
  steps: <TutorialStep>[
    TutorialTextStep(
      title: '为什么需要它',
      body: <String>[
        '局域网同步要求两台设备同时连在同一个 Wi-Fi 下，手机息屏后还经常连不上。',
        '全平台同步换成"把数据放进你自己的网盘"：在教室、在家里、在外面，只要联网就能同步。',
        '它不经过 Elychron 的服务器（我们也没有服务器）——数据只在你的设备和你的网盘之间走。',
      ],
    ),
    TutorialTipsStep(
      title: '开始之前，先准备三样',
      tips: <String>[
        '一个坚果云账号（免费版就够：每月上传 1GB、下载 3GB）',
        '装坚果云客户端生成一个「应用密码」（不是登录密码；网页版已经不给生成了）',
        '两台设备都填「同一个账号」，才能互相同步',
      ],
    ),
    TutorialTextStep(
      title: '第 1 步：选一个网盘',
      body: <String>[
        '设置 → 数据 → 全平台同步，第一步是选网盘。',
        '选坚果云，地址会自动填好；用 Alist、自建服务器或别的网盘就选"其他 / 自建"，自己贴地址。',
      ],
    ),
    TutorialTextStep(
      title: '第 2 步：填账号',
      body: <String>[
        '这里要填的是「应用密码」，不是登录密码。',
        '应用密码是专门给第三方程序用的，随时可以单独删掉，泄露了也不影响你的账号。',
        '应用密码只能在坚果云客户端里生成：设置 → 安全选项 → 第三方应用管理 → 添加应用密码。'
            '这里那个按钮会跳到坚果云下载页。',
        '坚果云的用户名必须全小写（大写会连不上）——你边打它边帮你转，不用自己操心。',
      ],
    ),
    TutorialTextStep(
      title: '第 3 步：试一下',
      body: <String>[
        '点"测试连接"：Elychron 会在你的网盘上真的建一个文件夹、写一个小文件再读回来。',
        '能通过就说明这台设备以后同步没问题，接着点"保存并开始同步"，立刻就会同步一次。',
      ],
    ),
    TutorialTipsStep(
      title: '之后会看到什么',
      tips: <String>[
