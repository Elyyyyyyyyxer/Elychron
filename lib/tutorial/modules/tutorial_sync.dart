        '切回 App 时会立刻查一次，也可以下拉待办页手动同步。',
        '「提示 HTTP 503？」——那是坚果云在限流（短时间请求太多），Elychron 会自己退避 30 分钟再试，',
        '不是你的账号坏了，过一会儿就好。',
        '「断开同步会删网盘上的数据吗？」——不会。只清本机的账号，网盘上的数据不动，',
        '重新填一遍账号还能接着用。',
      ],
    ),
    TutorialTextStep(
      title: '那就同步起来吧',
      body: <String>[
